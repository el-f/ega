export type { SettingsTab };

/** `action` is a button that does something once (reset, clear, delete), not a value. */
export type SettingType = 'toggle' | 'slider' | 'select' | 'text' | 'template' | 'group' | 'action';

export type AdvancedSubTab = 'diagnostics' | 'data';

/** `fallback` is the shipped default the stored value is compared against by value.
 *  `custom.paths` lists what `fn` reads — the coverage gate cannot see inside it. */
export type IsModifiedSpec =
  | { kind: 'eq'; path: string }
  | { kind: 'fallback'; path: string; fallback: number }
  | { kind: 'nonEmpty'; path: string }
  | { kind: 'jsonStringify'; path: string }
  | { kind: 'custom'; paths: readonly string[]; fn: (s: Settings) => boolean };

export interface SettingEntrySpec {
  readonly id: string;
  readonly label: string;
  readonly description: string;
  readonly keywords: readonly string[];
  readonly tab: SettingsTab;
  readonly subTab?: AdvancedSubTab;
  /** Lives outside every tab: Enter in search focuses it there. */
  readonly location?: 'header';
  readonly targetSelector?: string;
  readonly type: SettingType;
  readonly defaultValue?: string;
  readonly isModified?: IsModifiedSpec;
}

